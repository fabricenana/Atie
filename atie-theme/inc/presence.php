/**
 * Live trials on the page (one minute, microphone), switched on in the Customizer.
 *
 * @return bool
 */
function atie_presence_trials_enabled() {
	return (bool) get_theme_mod( 'atie_presence_trials', false );
}

/**
 * Public address of the ATIE trials API (no trailing slash). Filter: atie_presence_api_url.
 *
 * @return string
 */
function atie_presence_api_url() {
	return untrailingslashit( (string) apply_filters( 'atie_presence_api_url', 'https://console.atie.ch/presence-api' ) );
}

/**
 * Customizer: live trials switch, one image per receptionist.
 *
 * @param WP_Customize_Manager $wp_customize Customizer.
 */
function atie_presence_customize_register( $wp_customize ) {
	$wp_customize->add_section(
		'atie_presence',
		array(
			'title'       => __( 'ATIE Presence', 'atie' ),
			'description' => __( 'Portraits des réceptionnistes de la page ATIE Presence (format vertical 3:4 conseillé). Sans image choisie, le portrait fourni avec le thème est utilisé. Uniquement des visuels dont vous avez les droits.', 'atie' ),
			'priority'    => 31,
		)
	);

	$wp_customize->add_setting(
		'atie_presence_trials',
		array(
			'default'           => false,
			'sanitize_callback' => 'wp_validate_boolean',
		)
	);
	$wp_customize->add_control(
		'atie_presence_trials',
		array(
			'type'        => 'checkbox',
			'section'     => 'atie_presence',
			'label'       => __( 'Essais en direct (1 minute, micro)', 'atie' ),
			'description' => __( 'Les visiteurs parlent une minute avec Léa ou Maya. Chaque essai est facturé par LiveKit et LemonSlice : quotas par visiteur et par jour sur le serveur. Décoché : aucun essai, la page mène au contact.', 'atie' ),
		)
	);

	foreach ( array( 'lea' => 'Léa', 'maya' => 'Maya' ) as $id => $name ) {
		$wp_customize->add_setting(
			'atie_presence_image_' . $id,
			array(
				'default'           => 0,
				'sanitize_callback' => 'absint',
			)
		);
		$wp_customize->add_control(
			new WP_Customize_Media_Control(
				$wp_customize,
				'atie_presence_image_' . $id,
				array(
					/* translators: %s: receptionist name. */
					'label'     => sprintf( __( 'Image de %s', 'atie' ), $name ),
					'section'   => 'atie_presence',
					'mime_type' => 'image',
				)
			)
		);
	}
}
add_action( 'customize_register', 'atie_presence_customize_register' );

/**
 * Page styles and widget, only where the template is used.
 */
function atie_presence_assets() {
	if ( ! is_page_template( ATIE_PRESENCE_TEMPLATE ) ) {
		return;
	}

	wp_enqueue_style( 'atie-presence', ATIE_URI . '/assets/css/presence.css', array( 'atie-main' ), ATIE_VERSION );
	// Reduced motion: card videos stay still (with or without live trials).
	wp_register_script( 'atie-presence-page', false, array(), ATIE_VERSION, array( 'in_footer' => true ) );
	wp_enqueue_script( 'atie-presence-page' );
	wp_add_inline_script(
		'atie-presence-page',
		"(function(){if(window.matchMedia&&matchMedia('(prefers-reduced-motion: reduce)').matches)document.querySelectorAll('.presence-card video').forEach(function(v){v.removeAttribute('autoplay');v.pause();});})();"
	);

	if ( ! atie_presence_trials_enabled() ) {
		return;
	}
	wp_enqueue_script( 'atie-presence-widget', ATIE_URI . '/assets/presence/atie-presence.js', array(), ATIE_VERSION, array( 'in_footer' => true ) );

	// Buttons open the widget (with the chosen receptionist); cards without image get the widget drawing;
	// "leave a message" leads to the contact page.
	$personas = array();
	foreach ( atie_presence_personas() as $persona ) {
		$personas[ $persona['id'] ] = array(
			'name'    => $persona['name'],
			'image'   => $persona['image'],
			'video'   => $persona['video'],
			'variant' => $persona['variant'],
			'tenant'  => $persona['tenant'],
		);
	}
	$data    = wp_json_encode( $personas );
	$contact = wp_json_encode( atie_presence_contact_url() );
	wp_add_inline_script(
		'atie-presence-widget',
		"(function(){var P={$data},A=window.AtiePresence;if(!A)return;" .
				"document.querySelectorAll('[data-presence-face]').forEach(function(el){el.innerHTML=A.faceMarkup(el.getAttribute('data-presence-face'));el.firstChild.setAttribute('preserveAspectRatio','xMidYMid slice');});" .
		"document.querySelectorAll('[data-presence-open]').forEach(function(b){b.addEventListener('click',function(){var id=b.getAttribute('data-presence-open');if(id&&P[id])A.setPersona(P[id]);A.open();});});" .
		"document.addEventListener('atie:fallback',function(){window.location.href={$contact};});})();"
	);
}
add_action( 'wp_enqueue_scripts', 'atie_presence_assets' );

/**
 * Widget options as data- attributes on its script tag.
 *
 * @param string $tag    Script tag.
 * @param string $handle Script handle.
 * @return string
 */
function atie_presence_script_attributes( $tag, $handle ) {
	if ( 'atie-presence-widget' !== $handle ) {
		return $tag;
	}

	$lang     = substr( (string) get_bloginfo( 'language' ), 0, 2 );
	$personas = atie_presence_personas();
	$first    = $personas[0];
	$attrs    = sprintf(
		' data-api="%s" data-tenant="%s" data-avatar-name="%s" data-avatar-variant="%s" data-lang="%s"%s%s',
		esc_url( atie_presence_api_url() ),
		esc_attr( $first['tenant'] ),
		esc_attr( $first['name'] ),
		esc_attr( $first['variant'] ),
		esc_attr( in_array( $lang, array( 'fr', 'de', 'it', 'en' ), true ) ? $lang : 'fr' ),
		$first['image'] ? ' data-avatar-image="' . esc_url( $first['image'] ) . '"' : '',
		$first['video'] ? ' data-idle-src="' . esc_url( $first['video'] ) . '"' : ''
	);

	return preg_replace( '/<script(?=[^>]*\sid=["\']atie-presence-widget-js["\'])/', '<script' . $attrs, $tag, 1 );
}
add_filter( 'script_loader_tag', 'atie_presence_script_attributes', 10, 2 );

/**
 * Dark showcase styling hook on the ATIE Presence page.
 *
 * @param string[] $classes Body classes.
 * @return string[]
 */
function atie_presence_body_class( $classes ) {
	if ( is_page_template( ATIE_PRESENCE_TEMPLATE ) ) {
		$classes[] = 'atie-presence-dark';
	}

	return $classes;
}
add_filter( 'body_class', 'atie_presence_body_class' );
