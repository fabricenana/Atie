/**
 * Contact page URL (page with the "contact" slug), or the site home as fallback.
 *
 * @return string
 */
function atie_presence_contact_url() {
	$page = get_page_by_path( 'contact' );

	return $page ? get_permalink( $page ) : home_url( '/' );
}

